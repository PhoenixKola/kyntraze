def degree(scale, d): o, i = divmod(d, len(scale)); return scale[i] + 12 * o
def render(name, p):
    bpm, root, sc = p['bpm'], p['root'], p['scale']; beat = 60 / bpm; bar = beat * 4; total = bar * p['bars']; buf = np.zeros((int(total * SR) + SR, 2))
    for b in range(p['bars']):
        ch = p['chords'][b % len(p['chords'])]; at = b * bar
        for k, off in enumerate([0, 2, 4]):                                   # pad: a triad built on the chord degree
            f = mtof(root + degree(sc, ch + off) - 12 + (12 if k == 2 else 0)); s = tone(f, bar * 1.02, 'saw' if p['lead'] != 'sine' else 'sine', vib=0.4, bright=0.5)
            add(buf, at, lowpass(s, 22) * env(len(s), 0.4, 0.5, 0.7, 0.5), 0.10, (k - 1) * 0.3)
        add(buf, at, tone(mtof(root + degree(sc, ch) - 24), bar, 'sine') * env(int(bar * SR), 0.02, 0.2, 0.8, 0.1), 0.22)   # bass
        steps = len(p['arp']) * (2 if len(p['arp']) <= 4 else 1)
        for s_ in range(8):                                                   # arpeggio on eighth notes
            d = ch + p['arp'][s_ % len(p['arp'])] + (7 if b % 8 >= 4 and s_ % 4 == 3 else 0)
            a = tone(mtof(root + degree(sc, d) + 12), beat * 0.9, p['lead'], vib=0.2); add(buf, at + s_ * beat / 2, a * env(len(a), 0.005, 0.15, 0.4, 0.2), 0.12 if b % 4 else 0.15, 0.4 * (-1) ** s_)
        dr = p['drums']
        if dr != 'none':
            for q in range(4):
                t0 = at + q * beat
                if dr in ('soft', 'march', 'drive', 'epic', 'clock') and (q % 2 == 0 or dr == 'drive'): add(buf, t0, kick(), 0.35 if dr != 'soft' else 0.18)
                if dr in ('march', 'drive', 'epic') and q % 2 == 1: add(buf, t0, snare(), 0.22)
                if dr in ('skip', 'drive', 'clock', 'epic'): add(buf, t0 + beat / 2, hat(), 0.14); add(buf, t0, hat(), 0.09)
                if dr == 'skip' and q in (1, 3): add(buf, t0 + beat * 0.75, snare(), 0.14)
                if dr == 'clock': add(buf, t0 + beat / 4, hat(), 0.12); add(buf, t0 + beat * 0.75, hat(), 0.12)
        if name == 'sovereign' and b >= 16: add(buf, at, tone(mtof(root - 12 + degree(sc, ch)), bar, 'saw', bright=0.7) * env(int(bar * SR), 0.2, 0.2, 0.8, 0.2), 0.12)   # added layer for the last phase
    buf = buf[:int(total * SR)]; buf[:, 0] = lowpass(buf[:, 0], 2); buf[:, 1] = lowpass(buf[:, 1], 2)
    # gentle reverb-like tail (two delays) and loop-safe fades
    for dly, g in [(0.23, 0.22), (0.41, 0.14)]:
        k = int(dly * SR); buf[k:] += buf[:-k][::1] * g
    f = int(0.05 * SR); buf[:f] *= np.linspace(0, 1, f)[:, None]; buf[-f:] *= np.linspace(1, 0, f)[:, None]
    peak = np.abs(buf).max(); buf = buf / peak * 0.8; return buf
def stinger(name):
    n = {'coop_stinger': 2.2}[name]; buf = np.zeros((int(n * SR), 2))
    for i, (m, dt) in enumerate([(62, 0), (66, 0.12), (69, 0.24), (74, 0.36)]): s = tone(mtof(m), 1.6, 'bell'); add(buf, dt, s * env(len(s), 0.004, 0.3, 0.3, 0.5), 0.3, (-1) ** i * 0.4)
    s = tone(mtof(38), 2.0, 'saw', bright=0.6); add(buf, 0, lowpass(s, 16) * env(len(s), 0.05, 0.4, 0.5, 0.8), 0.25)
    return buf / np.abs(buf).max() * 0.8
def write_ogg(buf, name):
    wav = os.path.join(tempfile.gettempdir(), f'{name}.wav')
    with wave.open(wav, 'wb') as w: w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR); w.writeframes((np.clip(buf, -1, 1) * 32767).astype('<i2').tobytes())
    out = os.path.join(OUT, f'{name}.ogg'); subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', wav, '-c:a', 'libvorbis', '-q:a', '4', out], check=True); os.remove(wav)
    return out, os.path.getsize(out)
