"""B22 original score: procedural synthesis (numpy) -> OGG via ffmpeg. Every cue is composed from scratch here (chord progression, arpeggio, bass and percussion patterns per cue); no samples, no borrowed melodies. Run: python scripts/b22-synth.py  (writes public/audio/music/<cue>.ogg and a provenance note).
Provenance: original work generated by this script for KYNTRAZE: FRACTURE RUSH. Review by ear is still required (see B22-STATUS.md)."""
import os, subprocess, sys, tempfile, wave
import numpy as np

SR = 32000
OUT = os.path.join(os.path.dirname(__file__), '..', 'public', 'audio', 'music')
rng = np.random.default_rng(22)
mtof = lambda m: 440.0 * 2 ** ((m - 69) / 12)

def env(n, a=0.01, d=0.1, s=0.7, r=0.1):
    e = np.ones(n); na, nd, nr = int(a * SR), int(d * SR), int(r * SR)
    e[:na] = np.linspace(0, 1, max(1, na)); e[na:na + nd] = np.linspace(1, s, max(1, nd))[:max(0, n - na)]; e[na + nd:] = s
    if nr: e[-nr:] *= np.linspace(1, 0, nr)
    return e
def tone(f, dur, kind='saw', vib=0.0, bright=1.0):
    n = int(dur * SR); t = np.arange(n) / SR; ph = 2 * np.pi * f * t + vib * np.sin(2 * np.pi * 5 * t)
    if kind == 'sine': w = np.sin(ph)
    elif kind == 'saw': w = sum(np.sin(ph * k) / k for k in range(1, 7)) * 0.55 * bright
    elif kind == 'bell': w = np.sin(ph) + 0.5 * np.sin(ph * 2.76) * np.exp(-t * 3) + 0.3 * np.sin(ph * 5.4) * np.exp(-t * 5)
    elif kind == 'square': w = np.sign(np.sin(ph)) * 0.5 + 0.3 * np.sin(ph)
    elif kind == 'glass': w = np.sin(ph) + 0.6 * np.sin(ph * 3.01) * np.exp(-t * 2) + 0.4 * np.sin(ph * 4.99) * np.exp(-t * 4)
    else: w = np.sin(ph)
    return w
def add(buf, at, sig, gain=1.0, pan=0.0):
    i = int(at * SR); n = min(len(sig), len(buf) - i)
    if n <= 0: return
    buf[i:i + n, 0] += sig[:n] * gain * (1 - max(0, pan)); buf[i:i + n, 1] += sig[:n] * gain * (1 + min(0, pan))
def kick(): n = int(0.32 * SR); t = np.arange(n) / SR; f = 130 * np.exp(-t * 18) + 42; return np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 9)
def snare(): n = int(0.22 * SR); t = np.arange(n) / SR; return (rng.standard_normal(n) * 0.6 + np.sin(2 * np.pi * 190 * t) * 0.5) * np.exp(-t * 20)
def hat(): n = int(0.07 * SR); t = np.arange(n) / SR; x = rng.standard_normal(n); x = np.diff(x, prepend=0); return x * np.exp(-t * 60) * 0.5
def lowpass(x, k):
    c = np.cumsum(np.insert(x, 0, 0.0)); out = (c[k:] - c[:-k]) / k; return np.concatenate([np.full(k, out[0]), out])[:len(x)]

