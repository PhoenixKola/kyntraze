"""KYNTRAZE B05.1 - original ability sound design, synthesised from scratch (numpy only, deterministic seeds). No samples, no external packs, nothing copied.
  python synth_b05.py <out_dir> [--report]       -> 16-bit mono 44.1 kHz WAVs + loudness.json
Layers per sound: swept-filter noise (STFT band-pass), detuned saw/sine pads with pitch envelopes, sub body, crackle (sparse high-passed impulses), saturation, and a
synthetic room reverb (decaying filtered-noise impulse response). Solar (Form I) variants add a bright harmonic shimmer and extra sparkle on top of the same base.
Rights: all audio here is generated by this script (CC0-equivalent project asset, owner: the KYNTRAZE project)."""
import json, math, os, struct, sys, wave
import numpy as np

SR = 44100
def t_of(n): return np.arange(n) / SR
def rng(seed): return np.random.default_rng(seed)
def env_ad(n, a, d_pow=3.0):
    t = np.linspace(0, 1, n, endpoint=False); att = max(1, int(a * n)); e = np.ones(n)
    e[:att] = np.linspace(0, 1, att) ** 1.5; e[att:] = (1 - np.linspace(0, 1, n - att, endpoint=False)) ** d_pow; return e
def fade(x, i=0.004, o=0.01):
    n = len(x); a, b = int(i * SR), int(o * SR); x = x.copy()
    if a: x[:a] *= np.linspace(0, 1, a)
    if b: x[-b:] *= np.linspace(1, 0, b)
    return x
def noise(n, seed): return rng(seed).standard_normal(n)

def stft_filter(x, fc_curve, bw_oct, kind="bp", frame=1024, hop=256):
    """Time-varying filter: per STFT frame, gaussian band-pass (centre fc(t), width in octaves) or low-pass/high-pass at fc(t)."""
    n = len(x); w = np.hanning(frame); pad = np.pad(x, (frame, frame)); out = np.zeros(len(pad)); norm = np.zeros(len(pad)); fr = np.fft.rfftfreq(frame, 1 / SR); fr[0] = 1.0
    for s in range(0, len(pad) - frame, hop):
        c = fc_curve[min(n - 1, max(0, s - frame + frame // 2))]; spec = np.fft.rfft(pad[s:s + frame] * w)
        if kind == "bp": m = np.exp(-0.5 * (np.log2(fr / c) / (bw_oct / 2)) ** 2)
        elif kind == "lp": m = 1 / (1 + (fr / c) ** 4)
        else: m = 1 / (1 + (c / fr) ** 4)
        out[s:s + frame] += np.fft.irfft(spec * m, frame) * w; norm[s:s + frame] += w * w
    out = out / np.maximum(norm, 1e-6); return out[frame:frame + n]
def lin(a, b, n): return np.linspace(a, b, n)
def expc(a, b, n): return a * (b / a) ** np.linspace(0, 1, n)

def osc(freq_curve, kind="sine", detune=(0.0,), vib=(0, 0), phase0=0.0):
    n = len(freq_curve); out = np.zeros(n); t = t_of(n)
    for d in detune:
        f = freq_curve * (2 ** (d / 1200)) * (1 + vib[1] * np.sin(2 * math.pi * vib[0] * t)); ph = 2 * math.pi * np.cumsum(f) / SR + phase0
        if kind == "sine": out += np.sin(ph)
        elif kind == "saw": out += 2 * ((ph / (2 * math.pi)) % 1) - 1
        elif kind == "tri": out += 2 * np.abs(2 * ((ph / (2 * math.pi)) % 1) - 1) - 1
        elif kind == "harm": out += sum(np.sin(k * ph) / k for k in range(1, 8)) * 0.6
    return out / len(detune)
def crackle(n, density, seed, hp=2500):
    r = rng(seed); d = density if np.isscalar(density) else density; p = np.broadcast_to(d, n) / SR
    imp = (r.random(n) < p) * (r.standard_normal(n) * 1.0); k = np.exp(-np.arange(40) / 5.0); y = np.convolve(imp, k)[:n]
    return stft_filter(y, np.full(n, float(hp)), 1, "hp")
def reverb(x, rt=0.9, wet=0.3, seed=11, damp=3500):
    m = int(rt * SR); t = np.arange(m) / SR; ir = rng(seed).standard_normal(m) * np.exp(-6.9 * t / rt); ir = stft_filter(ir, np.full(m, float(damp)), 1, "lp")
    ir[:int(0.012 * SR)] *= np.linspace(0, 1, int(0.012 * SR)); n = len(x) + m; N = 1 << (n - 1).bit_length()
    y = np.fft.irfft(np.fft.rfft(x, N) * np.fft.rfft(ir, N), N)[:n]; y = y / (np.abs(y).max() + 1e-9) * np.abs(x).max()
    out = np.zeros(n); out[:len(x)] += x * (1 - wet * 0.6); out += y * wet; return out
def sat(x, drive): return np.tanh(x * drive) / math.tanh(drive)
def norm_to(x, peak_db): return x / (np.abs(x).max() + 1e-9) * 10 ** (peak_db / 20)
def trim(x, sec, fo):
    """Cut to `sec` seconds with a smooth `fo`-second fade-out so a reverb tail never outlives its gameplay window."""
    n = int(sec * SR); x = pad(x, n)[:n].copy(); m = int(fo * SR); x[-m:] *= np.cos(np.linspace(0, math.pi / 2, m)) ** 2; return x
def pad(x, n): return np.pad(x, (0, max(0, n - len(x))))[:n]

def solar_layer(n, seed, base=1800.0, gain=0.5):
    """Form I shimmer: a bright, slightly detuned harmonic stack with fast sparkle."""
    t = t_of(n); r = rng(seed); y = np.zeros(n)
    for k, f in enumerate((1.0, 1.5, 2.0, 3.0)): y += np.sin(2 * math.pi * base * f * t + r.random() * 6) * (0.6 ** k) * (0.6 + 0.4 * np.sin(2 * math.pi * (7 + 3 * k) * t))
    return y * gain * 0.18 + crackle(n, 220, seed + 5, 5000) * gain * 0.9

# ---------------------------------------------------------------- the sounds
def beam_charge(solar=False):
    n = int(0.5 * SR); t = t_of(n); u = np.linspace(0, 1, n)
    swell = u ** 2.2
    sweep = stft_filter(noise(n, 1), expc(350, 4200, n), 1.6) * swell * 1.4
    pad_ = osc(expc(110, 360, n), "saw", (-9, 0, 11), (5.5, 0.006)); pad_ = stft_filter(pad_, expc(500, 3400, n), 3) * swell * 0.9
    sub = osc(lin(48, 70, n), "sine") * swell * 0.7
    core = osc(expc(520, 1560, n), "sine", (-4, 4)) * swell ** 2.5 * 0.35
    cr = crackle(n, 30 + 700 * u ** 2, 4) * (0.5 + swell) * 1.2
    x = sweep + pad_ + sub + core + cr + (solar_layer(n, 9) * swell if solar else 0)
    return trim(fade(reverb(sat(x, 1.4), 0.25, 0.14), 0.01, 0.02), 0.6, 0.1)  # swell ends exactly at the 0.5 s release; short tail only

def beam_fire(solar=False):
    n = int(0.62 * SR); t = t_of(n)
    crack = stft_filter(noise(n, 7), np.full(n, 3200.0), 3, "hp") * np.exp(-t / 0.018) * 2.5
    boom = osc(expc(95, 42, n), "sine") * np.exp(-t / 0.30) * 1.6
    zap = stft_filter(osc(expc(2600, 220, n), "saw", (-12, 12)), expc(5200, 400, n), 2) * np.exp(-t / 0.10) * 1.2
    nb = int(0.5 * SR); bt = t_of(nb); fa = 190 * (1 + 0.012 * np.sin(2 * math.pi * 6 * bt))
    body = osc(fa, "saw", (-7, 0, 8)) + 0.7 * osc(fa * 2.003, "harm"); body = stft_filter(body, 900 + 700 * np.sin(2 * math.pi * 4 * bt) ** 2, 2.6)
    body += stft_filter(noise(nb, 8), np.full(nb, 1400.0), 1.8) * 0.5 + crackle(nb, 900, 10, 3000) * 0.8
    body *= np.minimum(1, bt / 0.04) * (1 - np.clip((bt - 0.38) / 0.12, 0, 1)); sub = osc(np.full(nb, 56.0), "sine") * 0.8 * np.minimum(1, bt / 0.03)
    bed = pad(body + sub, n) * 0.85
    x = crack + boom + zap + bed + (solar_layer(n, 12, 2200, 0.8) * np.exp(-t / 0.5) if solar else 0)
    return trim(fade(reverb(sat(x, 1.7), 0.3, 0.14), 0.001, 0.05), 0.62, 0.12)  # body gated at 0.5 s (= beam fire time); the 0.12 s tail is the only overhang

def beam_pulse(variant=0):
    n = int(0.16 * SR); t = t_of(n); k = (0.92, 1.0, 1.09)[variant % 3]
    z = stft_filter(noise(n, 20 + variant), np.full(n, 3000.0 * k), 2.2) * np.exp(-t / 0.035) * 2.0
    ping = osc(expc(1100 * k, 520 * k, n), "tri") * np.exp(-t / 0.05) * 0.9; thump = osc(expc(150 * k, 70, n), "sine") * np.exp(-t / 0.05) * 1.2
    return fade(sat(z + ping + thump, 1.5), 0.001, 0.02)

def beam_end():
    n = int(0.5 * SR); t = t_of(n)
    tail = stft_filter(noise(n, 30), expc(3200, 220, n), 2) * np.exp(-t / 0.13) * 1.4 + osc(expc(420, 70, n), "saw", (-8, 8)) * np.exp(-t / 0.12) * 0.5 + crackle(n, 500 * np.exp(-t / 0.14), 31) * 1.2
    return trim(fade(reverb(sat(tail, 1.3), 0.45, 0.22), 0.002, 0.04), 0.7, 0.25)

def sphere_gather(solar=False):
    n = int(0.8 * SR); t = t_of(n); u = np.linspace(0, 1, n); sw = u ** 1.8
    trem = 0.55 + 0.45 * np.sin(2 * math.pi * np.cumsum(lin(4, 15, n)) / SR)
    pad_ = osc(expc(86, 250, n), "sine", (-15, 0, 14), (0.7, 0.01)) + 0.5 * osc(expc(172, 500, n), "tri", (-6, 7)); pad_ *= trem * sw
    swirl = stft_filter(noise(n, 40), expc(220, 2600, n), 1.8) * sw * 1.3
    shim = sum(osc(expc(f0, f0 * 2.4, n), "sine", (0, 6)) * (0.5 / (i + 1)) for i, f0 in enumerate((420, 630, 840))) * sw ** 2.4 * 0.5
    sub = osc(lin(42, 62, n), "sine") * sw * 0.9; cr = crackle(n, 20 + 520 * u ** 2, 41) * (0.4 + sw) * 1.0
    x = pad_ * 1.2 + swirl + shim + sub + cr + (solar_layer(n, 43) * sw if solar else 0)
    return trim(fade(reverb(sat(x, 1.3), 0.35, 0.16), 0.02, 0.03), 0.95, 0.15)  # swell peaks at the 0.8 s throw

def sphere_throw():
    n = int(0.34 * SR); t = t_of(n)
    wh = stft_filter(noise(n, 50), expc(3000, 380, n), 1.4) * env_ad(n, 0.05, 1.8) * 2.0
    thump = osc(expc(130, 48, n), "sine") * np.exp(-t / 0.10) * 1.5; ping = osc(expc(1500, 600, n), "tri", (-10, 10)) * np.exp(-t / 0.06) * 0.7
    return trim(fade(reverb(sat(wh + thump + ping, 1.5), 0.3, 0.15), 0.001, 0.03), 0.5, 0.16)

def sphere_flight():
    n = int(0.55 * SR); t = t_of(n); u = np.linspace(0, 1, n)
    whistle = osc(expc(1100, 260, n), "tri", (-9, 9), (11, 0.01)) * 0.7 + stft_filter(noise(n, 60), expc(1800, 300, n), 1.6) * 0.8
    whistle += osc(expc(140, 70, n), "saw", (-6, 6)) * 0.4
    e = np.minimum(1, t / 0.03) * (1 - u) ** 0.6 * (0.7 + 0.3 * np.sin(2 * math.pi * 17 * t))
    return fade(sat(whistle * e, 1.3), 0.002, 0.06)

def sphere_burst(solar=False):
    n = int(2.0 * SR); t = t_of(n)
    crack = stft_filter(noise(n, 70), np.full(n, 2800.0), 3, "hp") * np.exp(-t / 0.03) * 3.0
    boom = osc(expc(70, 30, n), "sine") * np.exp(-t / 0.55) * 2.2; boom2 = osc(expc(130, 50, n), "sine", (-5, 5)) * np.exp(-t / 0.22) * 1.4
    body = stft_filter(noise(n, 71), expc(3200, 160, n), 2.2) * np.exp(-t / 0.28) * 2.2
    bloom = sum(osc(expc(f0, f0 * 0.5, n), "sine", (-6, 6)) / (i + 1) for i, f0 in enumerate((440, 660, 880, 1320))) * (1 - np.exp(-t / 0.05)) * np.exp(-t / 0.55) * 0.5
    debris = crackle(n, 900 * np.exp(-t / 0.55), 72, 1800) * 1.6
    x = crack + boom + boom2 + body + bloom + debris + (solar_layer(n, 73, 2000, 1.0) * np.exp(-t / 0.7) if solar else 0)
    return trim(fade(reverb(sat(x, 2.0), 1.0, 0.32, 74), 0.001, 0.12), 2.3, 0.5)

def cast_cancel():
    n = int(0.28 * SR); t = t_of(n)
    f = stft_filter(noise(n, 80), expc(2600, 180, n), 1.8) * np.exp(-t / 0.07) * 1.4 + osc(expc(300, 60, n), "saw", (-9, 9)) * np.exp(-t / 0.08) * 0.8 + crackle(n, 600 * np.exp(-t / 0.08), 81) * 1.2
    return fade(sat(f, 1.4), 0.001, 0.03)

