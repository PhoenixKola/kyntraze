"""Measure the fist anchors for all 8 direction x form combinations and publish them:
  python build_anchors.py   ->  abilities/anchors/hand-anchors.json, public/art/kai-anchors.json, src/content/handAnchors.ts
Anchors are in exported sprite px relative to the manifest ground origin; `m` = midpoint of the two fists (the muzzle / orb point)."""
import json, os, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__)); AB = os.path.dirname(HERE); REPO = os.path.abspath(os.path.join(AB, "..", "..", "..", ".."))
out = {"schema": "kyntraze.hand-anchors/1", "unit": "sprite px relative to the manifest ground origin (x right, y down)", "fist": "centroid of the visible fist art", "forms": {}}
for form in ("base", "f1"):
    out["forms"][form] = {}
    for d in ("south", "north", "east", "west"):
        r = subprocess.run([sys.executable, os.path.join(HERE, "hand_anchors.py"), d, form], capture_output=True, text=True)
        if r.returncode: print(r.stderr[-1500:]); sys.exit(1)
        j = json.loads(r.stdout)
        for clip in j:
            for fr in j[clip]: fr["m"] = [round((fr["n"][0] + fr["f"][0]) / 2, 2), round((fr["n"][1] + fr["f"][1]) / 2, 2)]
        out["forms"][form][d] = j
out["forms"]["f2"] = json.loads(json.dumps(out["forms"]["f1"]))   # Form II shares the Form I rig hands (only head/hair art differs; anchors are ground-origin relative)
json.dump(out, open(os.path.join(AB, "anchors", "hand-anchors.json"), "w"), separators=(",", ":"))
json.dump(out, open(os.path.join(REPO, "public", "art", "kai-anchors.json"), "w"), separators=(",", ":"))
# release-frame constants the SIM uses (so the damaging lane starts where the visible fists are): beam = mean of the fire-hold frames, sphere = the throw frame
ts = ["// GENERATED by art/characters/kai/abilities/scripts/build_anchors.py - do not edit. Sprite px relative to the ground origin (x right, y down).",
      "export type Face = 'south' | 'north' | 'east' | 'west';", "export interface Pt { x: number; y: number }"]
def table(name, pick):
    ts.append(f"export const {name}: Record<'base' | 'f1' | 'f2', Record<Face, Pt>> = {{")
    for form in ("base", "f1", "f2"):
        ts.append(f"  {form}: {{ " + ", ".join(f"{d}: {{ x: {pick(out['forms'][form][d], d)[0]:.2f}, y: {pick(out['forms'][form][d], d)[1]:.2f} }}" for d in ("south", "north", "east", "west")) + " },")
    ts.append("};")
mean = lambda fr: [sum(f["m"][i] for f in fr) / len(fr) for i in (0, 1)]
def punch(j, d):   # the fist that leads along the facing axis at the BasicPunch impact frame (frame 5)
    f = j["BasicPunch"][5]; k = {"east": lambda p: p[0], "west": lambda p: -p[0], "south": lambda p: p[1], "north": lambda p: -p[1]}[d]; return max((f["n"], f["f"]), key=k)
table("BEAM_MUZZLE", lambda j, d: mean(j["Beam"][10:20])); table("SPHERE_RELEASE", lambda j, d: j["Sphere"][16]["m"]); table("PUNCH_FIST", punch)
open(os.path.join(REPO, "src", "content", "handAnchors.ts"), "w").write("\n".join(ts) + "\n")
print(open(os.path.join(REPO, "src", "content", "handAnchors.ts")).read())
